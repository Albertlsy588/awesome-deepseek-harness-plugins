#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import { assert, isObject, readCategories } from './lib/catalog-entry.mjs'

const scriptRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const defaultBase = 'https://deepseek1024.com'
// Must stay aligned with UNCLASSIFIED_CATEGORY in apps/web/worker/lib/categories.ts
// (the website/API label for the same bucket); the .mjs script cannot import Worker TS.
const unclassifiedLabel = { en: 'Unclassified', zh: '待分类' }
const generatedNotice = {
  zh: '<!-- 本文件由 scripts/build-readme.mjs 从 deepseek1024.com 目录 API 自动生成，请勿手工编辑。 -->',
  en: '> This file is generated by `scripts/build-readme.mjs` from the DSH 1024Store catalog API. Do not edit it directly.',
}

function text(value) {
  return typeof value === 'string' ? value.replace(/\s+/g, ' ').trim() : ''
}

function updatedDate(value) {
  const date = typeof value === 'string' ? value.slice(0, 10) : ''
  assert(/^\d{4}-\d{2}-\d{2}$/.test(date), `Registry has an invalid updated timestamp: ${String(value)}`)
  return date
}

function normalizePlugin(plugin, id, stars) {
  assert(isObject(plugin), 'Registry contains an invalid plugin entry')
  const name = text(plugin.name)
  const url = typeof plugin.url === 'string' ? plugin.url : ''
  assert(name.length > 0 && /^https:\/\/github\.com\//.test(url), `Registry plugin ${id} must have a name and GitHub url`)
  return {
    id,
    name,
    owner: text(plugin.owner),
    url,
    category: typeof plugin.category === 'string' && plugin.category.length > 0 ? plugin.category : 'unclassified',
    description: {
      en: text(plugin.description?.en),
      zh: text(plugin.description?.zh),
    },
    added: typeof plugin.added === 'string' ? plugin.added : null,
    stars,
  }
}

export function normalizeRegistry(data) {
  assert(isObject(data) && Array.isArray(data.plugins), 'Registry response must contain a plugins array')
  return {
    updated: updatedDate(data.updated),
    plugins: data.plugins.map(plugin => {
      assert(isObject(plugin) && typeof plugin.id === 'string' && /^[^/]+\/[^/]+$/.test(plugin.id), 'Registry plugins must carry an owner/repository id')
      return normalizePlugin(plugin, plugin.id, Number.isInteger(plugin.stars) ? plugin.stars : null)
    }),
  }
}

export function adaptLegacyRegistry(data) {
  assert(isObject(data) && Array.isArray(data.plugins), 'Legacy /plugins.json must contain a plugins array')
  return {
    updated: updatedDate(data.updated),
    plugins: data.plugins.map(plugin => {
      assert(isObject(plugin) && typeof plugin.url === 'string', 'Legacy plugins must carry a url')
      const derived = new URL(plugin.url).pathname.replace(/^\/+/, '').replace(/\/+$/, '')
      const id = /^[^/]+\/[^/]+$/.test(derived) ? derived : `${plugin.owner}/${plugin.name}`
      return normalizePlugin(plugin, id, null)
    }),
  }
}

function detectRegistryShape(data) {
  const plugins = isObject(data) ? data.plugins : undefined
  const first = Array.isArray(plugins) ? plugins.find(value => isObject(value)) : undefined
  if (first !== undefined && typeof first.id !== 'string') return adaptLegacyRegistry(data)
  return normalizeRegistry(data)
}

export async function loadRegistry(options = {}) {
  if (options.fromFile !== undefined) {
    return detectRegistryShape(JSON.parse(await readFile(options.fromFile, 'utf8')))
  }
  const fetchImplementation = options.fetchImplementation ?? globalThis.fetch
  const base = (options.base ?? defaultBase).replace(/\/+$/, '')
  const registryResponse = await fetchImplementation(`${base}/api/v1/registry`)
  if (registryResponse.ok) {
    return normalizeRegistry(JSON.parse(await registryResponse.text()))
  }
  if (registryResponse.status !== 404) {
    throw new Error(`GET ${base}/api/v1/registry failed: HTTP ${registryResponse.status}`)
  }
  const legacyResponse = await fetchImplementation(`${base}/plugins.json`)
  if (!legacyResponse.ok) {
    throw new Error(`GET ${base}/plugins.json fallback failed: HTTP ${legacyResponse.status}`)
  }
  return adaptLegacyRegistry(JSON.parse(await legacyResponse.text()))
}

function comparePlugins(left, right) {
  const leftName = left.name.toLocaleLowerCase('en-US')
  const rightName = right.name.toLocaleLowerCase('en-US')
  return leftName.localeCompare(rightName, 'en-US')
    || left.name.localeCompare(right.name, 'en-US')
    || left.id.localeCompare(right.id, 'en-US')
}

export function groupPlugins(registry, categories) {
  const ordered = [...categories].sort((left, right) => (left.order ?? 0) - (right.order ?? 0) || String(left.id).localeCompare(String(right.id), 'en-US'))
  const buckets = new Map(ordered.map(category => [category.id, []]))
  const unclassified = []
  for (const plugin of registry.plugins) {
    (buckets.get(plugin.category) ?? unclassified).push(plugin)
  }
  const groups = ordered
    .filter(category => buckets.get(category.id).length > 0)
    .map(category => ({
      id: category.id,
      label: category.label,
      plugins: [...buckets.get(category.id)].sort(comparePlugins),
    }))
  if (unclassified.length > 0) {
    groups.push({ id: 'unclassified', label: unclassifiedLabel, plugins: [...unclassified].sort(comparePlugins) })
  }
  return groups
}

function pluginLine(plugin, locale) {
  const preferred = plugin.description[locale]
  const fallback = locale === 'zh' ? plugin.description.en : plugin.description.zh
  const description = preferred.length > 0 ? preferred : fallback
  return description.length > 0
    ? `- [${plugin.name}](${plugin.url}) — ${description}`
    : `- [${plugin.name}](${plugin.url})`
}

function categoryIndex(groups, locale) {
  return groups.map(group => `- [${group.label[locale]}](#${group.id}) (${group.plugins.length})`).join('\n')
}

function categorySections(groups, locale) {
  return groups.map(group => [
    `<a id="${group.id}"></a>`,
    '',
    `## ${group.label[locale]}`,
    '',
    group.plugins.map(plugin => pluginLine(plugin, locale)).join('\n'),
  ].join('\n')).join('\n\n')
}

