export async function buildReadmeFiles(registry, categories) {
  const groups = groupPlugins(registry, categories)
  return {
    'README.md': chineseReadme(registry, groups),
    'catalog/README.md': englishReadme(registry, groups),
  }
}

export function parseArguments(argv) {
  const options = { root: scriptRoot, base: defaultBase, check: false, help: false }
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    const value = () => {
      const next = argv[index + 1]
      if (next === undefined || next.startsWith('--')) throw new Error(`${argument} requires a value`)
      index += 1
      return next
    }
    if (argument === '--base') options.base = value()
    else if (argument === '--from-file') options.fromFile = path.resolve(value())
    else if (argument === '--root') options.root = path.resolve(value())
    else if (argument === '--check') options.check = true
    else if (argument === '--help' || argument === '-h') options.help = true
    else throw new Error(`Unknown argument: ${argument}`)
  }
  return options
}

function usage() {
  return `Usage: npm run readme:build [-- options]

Regenerates README.md (Chinese) and catalog/README.md (English) from the full
DSH 1024Store catalog: GET <base>/api/v1/registry, falling back to the legacy
<base>/plugins.json shape when the v1 endpoint is not deployed yet.

Options:
  --base <url>        Catalog API origin (default: ${defaultBase})
  --from-file <json>  Build from a local registry JSON file instead of the network
  --root <path>       Repository root for categories.json and output files
  --check             Verify the committed files are current; do not write
  --help              Show this help`
}

async function main() {
  const options = parseArguments(process.argv.slice(2))
  if (options.help) {
    console.log(usage())
    return
  }
  const categories = await readCategories(options.root)
  const registry = await loadRegistry(options)
  assert(
    registry.plugins.length > 0,
    'Registry returned 0 plugins; refusing to regenerate README projections from a degenerate snapshot.',
  )
  const files = await buildReadmeFiles(registry, categories)

  if (options.check) {
    const stale = []
    for (const [relative, content] of Object.entries(files)) {
      const existing = await readFile(path.join(options.root, relative), 'utf8').catch(() => '')
      if (existing !== content) stale.push(relative)
    }
    if (stale.length > 0) {
      console.error(`Stale generated files: ${stale.join(', ')}. Run npm run readme:build.`)
      process.exitCode = 1
      return
    }
    console.log('README projections are up to date.')
    return
  }

  for (const [relative, content] of Object.entries(files)) {
    await writeFile(path.join(options.root, relative), content)
    console.log(`Wrote ${relative} (${registry.plugins.length} plugins, updated ${registry.updated})`)
  }
}

if (process.argv[1] !== undefined && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  try {
    await main()
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error))
    process.exitCode = 1
  }
}
